def git(root: Path, *args: str) -> str:
    env = dict(
        os.environ,
        GIT_AUTHOR_NAME="Sample", GIT_AUTHOR_EMAIL="sample@example.com",
        GIT_COMMITTER_NAME="Sample", GIT_COMMITTER_EMAIL="sample@example.com",
    )  # fmt: skip
    out = subprocess.run(["git", *args], cwd=root, env=env, capture_output=True, check=True)
    return out.stdout.decode("utf-8")


def write_tree(root: Path, tree: dict[str, str], removed: set[str]) -> None:
    for name in removed:
        (root / name).unlink(missing_ok=True)
    for name, text in tree.items():
        target = root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))


def build_diff() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        git(root, "init", "-q", "-b", "main")
        git(root, "config", "core.autocrlf", "false")
        write_tree(root, BASE, set())
        git(root, "add", "-A")
        git(root, "commit", "-q", "-m", "base")
        write_tree(root, HEAD, set(BASE) - set(HEAD))
        git(root, "add", "-A")
        git(root, "commit", "-q", "-m", "head")
        return git(root, "diff", "--no-color", "-M", "HEAD~1", "HEAD")


def render(diff: str) -> str:
    lines = diff.rstrip("\n").split("\n")
    body = ",\n".join(f"  {json.dumps(line, ensure_ascii=False)}" for line in lines)
    return (
        "// Generated by scripts/gen_sample_diff.py. Edit the script, not this file.\n"
        "// The diff is a made-up payments service with a handful of the changes ChangeRisk is\n"
        "// meant to catch. The key is assembled here so no string in the repository looks like one.\n\n"
        f"const LINES = [\n{body}\n];\n\n"
        "const FAKE_KEY = 'sk_' + 'live_' + '51Hq7LKd2eZvKYlo2C0xv9nTq8RbW3mA';\n\n"
        "export const SAMPLE_DIFF = LINES.join('\\n').replace('__STRIPE_KEY__', FAKE_KEY) + '\\n';\n"
    )


def main() -> int:
    TARGET.write_text(render(build_diff()), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


